"""Свободный режим: Капри комментирует что угодно и когда угодно, при желании матом, и умеет «смотреть» на обои и экран.

Что здесь:
- «свободный режим» (`"commentary_anytime": true`): реплики чаще, без оглядки на полноэкранные программы, плюс случайные
  комментарии к тому, чем ты занят прямо сейчас, к безделью («ты там уснул?») и к возвращению за компьютер;
- мат (`"profanity": true`): подколки и ответы на победу/поражение идут с русским матом. Ругает ситуацию и поступки,
  а не национальность, внешность, пол или здоровье. По умолчанию выключено: включается голосом («Капри, ругайся»)
  или галочкой в трее;
- обои и экран: нужна локальная модель с «глазами» в Ollama (например `ollama pull qwen2.5vl:3b` или `gemma3:4b`).
  Картинка уменьшается и уходит только в Ollama на этом же компьютере (127.0.0.1), нигде не сохраняется и в журнал не
  попадает; режим Claude для этого не используется. «Капри, прокомментируй обои» и «Капри, прокомментируй экран» —
  по просьбе, всегда; самой по себе (когда обои сменились или иногда в свободном режиме) она смотрит на обои, только если
  включено `"commentary_wallpaper": true`. Экран сам по себе она для комментариев не снимает, только когда ты попросил."""
