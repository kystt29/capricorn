# ---------------- обои и экран ----------------

def wallpaper_path():
    """Путь к файлу обоев рабочего стола или None (однотонный фон, слайдшоу без файла). Только Windows."""
    import ctypes
    buf = ctypes.create_unicode_buffer(520)
    try:
        if ctypes.windll.user32.SystemParametersInfoW(0x73, 520, buf, 0) and buf.value and os.path.isfile(buf.value):
            return buf.value
    except Exception:
        pass
    transcoded = os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows", "Themes", "TranscodedWallpaper")
    return transcoded if os.path.isfile(transcoded) else None


def wallpaper_signature():
    """Отпечаток текущих обоев (путь, время изменения, размер) — чтобы заметить, что их сменили. None — обоев нет."""
    path = wallpaper_path()
    if not path:
        return None
    try:
        st = os.stat(path)
    except OSError:
        return None
    return (path, st.st_mtime_ns, st.st_size)


def image_b64(source, max_side=640):
    """Картинка (путь или объект PIL) → уменьшенный JPEG в base64 для локальной модели. Нигде не сохраняется."""
    from PIL import Image
    img = source if hasattr(source, "convert") else Image.open(source)
    img = img.convert("RGB")
    img.thumbnail((max_side, max_side))
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=80)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def describe(local, kind):
    """Короткое описание обоев (kind="wallpaper") или экрана (kind="screen") от локальной модели с «глазами».
    None — нечего описывать; NoVision — модели с картинками нет."""
    if kind == "wallpaper":
        path = wallpaper_path()
        if not path:
            return None
        data = image_b64(path)
    else:
        from PIL import ImageGrab
        data = image_b64(ImageGrab.grab(), 800)
    return local.describe_image(data, kind)


