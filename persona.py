# Дополнительный контекст и темы для нейросети: сюда подключаются модули, например games.py.
CONTEXT_PROVIDERS = []   # функции без аргументов → строка с фактами о пользователе
TOPIC_PROVIDERS = []     # функции без аргументов → список тем для спонтанных реплик


# кто пользователь: пол ("male" / "female") и имя ("" — не называть). Ставит main из настроек.
USER = {"gender": "male", "name": ""}


def set_user(name, gender):
    USER["name"] = (name or "").strip()
    USER["gender"] = "female" if gender == "female" else "male"


def gendered(text):
    """[скучал|скучала] → слово в роде пользователя."""
    i = 1 if USER["gender"] == "female" else 0
    return re.sub(r"\[([^\[\]|]+)\|([^\[\]|]+)\]", lambda m: m.group(i + 1), text)


def line(key, **kw):
    variants = LINES[key]
    if not USER["name"]:  # без имени — только варианты без обращения по имени
        variants = [v for v in variants if "{name}" not in v] or variants
    return gendered(random.choice(variants)).format(name=USER["name"], **kw)


def user_context():
    """Для нейросети: кто пользователь и как к нему обращаться."""
    if USER["gender"] == "female":
        text = "Пользователь — девушка: обращайся к ней в женском роде (ты сказала, ты устала)."
    else:
        text = "Пользователь — парень: обращайся к нему в мужском роде (ты сказал, ты устал)."
    if USER["name"]:
        text += (f" Пользователя зовут {USER['name']}. Иногда, не в каждом ответе, обращайся по имени — "
                 f"вместо «чумба».")
    for provider in CONTEXT_PROVIDERS:
        try:
            extra = provider()
        except Exception:
            continue
        if extra:
            text += "\n" + extra
    return text


def extra_topics():
    """Темы для спонтанных реплик от подключённых модулей."""
    topics = []
    for provider in TOPIC_PROVIDERS:
        try:
            topics += provider()
        except Exception:
            continue
    return topics
